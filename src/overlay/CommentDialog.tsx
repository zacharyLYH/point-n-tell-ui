import { useState } from 'react';
import { Trash2 } from 'lucide-react';
import type { CaptureDraft, SessionState } from '../types.js';
import { sendJson, useAction } from './api.js';
import { CutCarousel, cutImages } from './CutCarousel.js';
import { Alert } from '../components/ui/alert.js';
import { Badge } from '../components/ui/badge.js';
import { Button } from '../components/ui/button.js';
import { Dialog, DialogContent, DialogDescription, DialogTitle } from '../components/ui/dialog.js';
import { Label } from '../components/ui/label.js';
import { Textarea } from '../components/ui/textarea.js';

/**
 * Shared post-capture step: review the captured images, add a comment, then
 * save or delete. Closing the dialog discards the pending capture.
 */
export function CommentDialog({
  apiUrl,
  draft,
  onDone,
}: {
  apiUrl: string;
  draft: CaptureDraft;
  onDone: (state: SessionState) => void;
}) {
  const kind = draft.kind;
  const isRecording = kind === 'recording';
  const id = kind === 'recording' ? draft.recording.recordingId : draft.selection.selectionId;
  const images = kind === 'recording' ? cutImages(draft.recording, true) : [{ id, label: 'Screenshot' }];
  const [comment, setComment] = useState(
    kind === 'recording' ? draft.recording.comment : draft.selection.comment,
  );
  const { busy, error, run } = useAction();

  // Both kinds save and discard through the same item routes.
  const settle = (method: 'PATCH' | 'DELETE', body?: unknown) =>
    void run(async () => onDone(await sendJson<SessionState>(`${apiUrl}/${kind}/${id}`, body, method)));

  return (
    <Dialog open onOpenChange={(open) => !open && settle('DELETE')}>
      <DialogContent
        className="flex max-h-[calc(100dvh-2rem)] w-full max-w-3xl flex-col gap-3 rounded-3xl p-5 font-sans text-foreground"
        onEscapeKeyDown={(event) => event.preventDefault()}
      >
        <DialogTitle className="text-sm font-semibold">
          {isRecording ? 'Save video capture' : 'Save screenshot capture'}
        </DialogTitle>
        <DialogDescription className="flex flex-wrap items-center gap-1.5 text-[11px] text-muted-foreground">
          {isRecording && (
            <Badge variant="success" data-testid="ffmpeg-status" title="Cuts generated by FFmpeg">
              FFmpeg ✓
            </Badge>
          )}
          <span>{isRecording ? 'Add a comment, then save or delete.' : 'Add a comment, then save or delete this capture.'}</span>
        </DialogDescription>

        <div className="flex justify-center overflow-auto">
          <CutCarousel apiUrl={apiUrl} images={images} />
        </div>

        <div className="space-y-2">
          <Label htmlFor="pnt-capture-comment" className="text-[11px] text-muted-foreground">
            Comment
          </Label>
          <Textarea
            id="pnt-capture-comment"
            aria-label="Capture comment"
            value={comment}
            onChange={(event) => setComment(event.target.value)}
            maxLength={5000}
            placeholder="What is wrong here?"
            className="min-h-20 resize-y text-xs"
          />
        </div>

        {error && <Alert variant="destructive">{error}</Alert>}

        <div className="flex items-center justify-between gap-2">
          <Button type="button" variant="destructive" size="sm" disabled={busy} onClick={() => settle('DELETE')}>
            <Trash2 aria-hidden="true" />
            Delete
          </Button>
          <Button
            type="button"
            size="sm"
            disabled={busy || !comment.trim()}
            onClick={() => settle('PATCH', { comment: comment.trim() })}
          >
            Save capture
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}
